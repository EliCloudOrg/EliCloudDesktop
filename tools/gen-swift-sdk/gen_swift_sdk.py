#!/usr/bin/env python3
"""从 contracts/openapi.yaml 生成 Swift API（apple/swift-openapi-generator）——Stage 4。

为什么用生成器而不是手写 DTO：
  - 契约是唯一协议源（Stage 1），DTO 手写必然漂移；生成物可 diff、可 --check；
  - 生成器直接产出 `Sendable` 的 struct + 显式 `CodingKeys`（snake_case 对应）
    与 async/await 客户端，Swift 6 严格并发下能过检查。

生成什么 / 不生成什么：
  - 生成：`Sources/EliCloudSDK/Generated/Types.swift`（schemas）+
    `Generated/Client.swift`（每个 operationId 一个方法）。
  - 不生成行为层：会话（actor SessionStore）、超时策略、错误映射、图片管线都在
    `Sources/EliCloudSDK/` 手写，见 sdks/swift/README.md。

用法：
    # 生成（有 swift 用 native，否则用本机 Docker 里的 swift 镜像）
    python tools/gen-swift-sdk/gen_swift_sdk.py

    # CI：只校验生成物没有漂移（契约改了却没重新生成 → 失败）
    python tools/gen-swift-sdk/gen_swift_sdk.py --check

    # 显式选择后端
    python tools/gen-swift-sdk/gen_swift_sdk.py --runner native   # macOS/Linux + swift
    python tools/gen-swift-sdk/gen_swift_sdk.py --runner docker   # 任意有 Docker 的机器

Docker 后端把所有缓存（生成器源码、SwiftPM build、HOME）放在仓库的 `.local/gen-swift-sdk`
（已 gitignore），不往 Docker Desktop 的虚拟机磁盘里堆东西。
"""

from __future__ import annotations

import argparse
import hashlib
import os
import shutil
import subprocess
import sys
from pathlib import Path

try:
    import yaml
except ImportError:  # pragma: no cover - 环境问题
    yaml = None

ROOT = Path(__file__).resolve().parents[2]
OPENAPI = ROOT / "contracts" / "openapi.yaml"
CONFIG = ROOT / "tools" / "gen-swift-sdk" / "openapi-generator-config.yaml"
OUTPUT = ROOT / "sdks" / "swift" / "Sources" / "EliCloudSDK" / "Generated"
CACHE = ROOT / ".local" / "gen-swift-sdk"

# 生成器输入 = 契约的“Swift 视图”，写在缓存目录里（不入库、不影响契约本身）。
DERIVED_INPUT_NAME = "openapi.swift.yaml"

# 版本 pin：生成器、运行时包、Swift 工具链三者对齐，避免 CI 漂移。
#   - 生成器 tag 必须等于 Package.swift 里 swift-openapi-runtime 的版本线；
#   - Swift 版本必须满足生成器要求（1.9.0 需要 Swift 6.0+）。
GENERATOR_REPO = "https://github.com/apple/swift-openapi-generator"
GENERATOR_VERSION = "1.9.0"
SWIFT_IMAGE = "swift:6.1-jammy"
SWIFT_IMAGE_MIRROR = "docker.m.daocloud.io/library/swift:6.1-jammy"

BANNER = """\
// <auto-generated>
// 由 tools/gen-swift-sdk/gen_swift_sdk.py 生成；输入 contracts/openapi.yaml。
// 生成器 apple/swift-openapi-generator {version}。**不要手改**：改契约后重新生成。
// </auto-generated>
"""

GENERATION_SCRIPT = """set -euo pipefail
mkdir -p "$CACHE_ROOT/home" "$CACHE_ROOT/tmp"
export HOME="$CACHE_ROOT/home"
export TMPDIR="$CACHE_ROOT/tmp"
export XDG_CACHE_HOME="$HOME/.cache"
generator="$CACHE_ROOT/swift-openapi-generator-$GENERATOR_VERSION"
if [ ! -f "$generator/Package.swift" ]; then
  rm -rf "$generator"
  git clone --depth 1 --branch "$GENERATOR_VERSION" {repo} "$generator"
fi
swift run --package-path "$generator" --scratch-path "$CACHE_ROOT/.build-$GENERATOR_VERSION" \\
  -c release swift-openapi-generator generate \\
  --config "$WORK/tools/gen-swift-sdk/openapi-generator-config.yaml" \\
  --diagnostics-output-path "$CACHE_ROOT/diagnostics.yaml" \\
  --output-directory "$WORK/$OUTPUT_REL" \\
  "$CACHE_ROOT/{derived_input}"
"""


class ToolError(RuntimeError):
    """工具自身或环境问题（不是生成物漂移）。"""


def log(message: str) -> None:
    print(f"[gen-swift-sdk] {message}", flush=True)


def run(cmd: list[str], *, cwd: Path | None = None, env: dict[str, str] | None = None) -> None:
    log("$ " + " ".join(cmd))
    subprocess.run(cmd, cwd=str(cwd) if cwd else None, env=env, check=True)


def to_docker_path(path: Path) -> str:
    """Windows 盘符路径转 Docker Desktop 能接受的挂载写法（D:\\a → D:/a）。"""
    return path.resolve().as_posix()


def generation_script() -> str:
    return GENERATION_SCRIPT.format(repo=GENERATOR_REPO, derived_input=DERIVED_INPUT_NAME)


def _is_null_schema(branch: object) -> bool:
    if not isinstance(branch, dict):
        return False
    schema_type = branch.get("type")
    if schema_type == "null":
        return True
    return isinstance(schema_type, list) and bool(schema_type) and set(schema_type) == {"null"}


def _downgrade_nullable_unions(node: object) -> int:
    """把 `oneOf/anyOf: [X, {type: 'null'}]` 就地换成 `X`，返回改动次数。

    只处理“恰好一个非 null 分支”的情形；其它形态原样保留（宁可让生成器报错，
    也不要悄悄改变契约语义）。
    """
    if isinstance(node, list):
        return sum(_downgrade_nullable_unions(item) for item in node)
    if not isinstance(node, dict):
        return 0
    count = 0
    for key in list(node.keys()):
        child = node[key]
        if key in ("oneOf", "anyOf") and isinstance(child, list):
            non_null = [branch for branch in child if not _is_null_schema(branch)]
            if len(non_null) == 1 and len(non_null) != len(child) and isinstance(non_null[0], dict):
                siblings = {k: v for k, v in node.items() if k != key}
                node.clear()
                node.update(siblings)
                node.update(non_null[0])
                count += 1
                continue
        count += _downgrade_nullable_unions(child)
    return count


def derive_generator_input(source: Path, destination: Path) -> int:
    """写生成器输入：契约原文 + 可空 union 降级（仅影响 Swift 生成器）。

    为什么需要：
      - 契约里 `avatar` / `banner` / `rcon` / `quota` / `user` 用
        `oneOf: [$ref, {type: 'null'}]` 表达“对象或 null”，这是 OAS 3.1 的正确写法，
        fixtures 里也确实出现显式 null；
      - 但 `apple/swift-openapi-generator` 1.9.0 把 `.null` 视为不支持的 schema
        （`case .not, .null: return .unsupported`），会**把整个字段静默跳过**；
      - 这些字段都不在 `required` 里，生成器对可选属性本来就会出 `T?`，
        所以把 union 降级为单个 `$ref` 之后，Swift 侧类型与解码行为完全一致
        （null → nil），而契约本身**一个字都不改**。
    """
    if yaml is None:
        raise ToolError("需要 pyyaml：python -m pip install --disable-pip-version-check pyyaml==6.0.2")
    document = yaml.safe_load(source.read_text(encoding="utf-8"))
    if not isinstance(document, dict):
        raise ToolError(f"{source} 顶层不是对象")
    rewrites = _downgrade_nullable_unions(document)
    destination.write_text(
        yaml.safe_dump(document, allow_unicode=True, sort_keys=False, width=4096),
        encoding="utf-8",
    )
    return rewrites


def ensure_docker_image() -> None:
    if shutil.which("docker") is None:
        raise ToolError("没找到 docker；要么装 Docker，要么在有 swift 的机器上跑 --runner native")
    probe = subprocess.run(
        ["docker", "image", "inspect", SWIFT_IMAGE], capture_output=True, text=True
    )
    if probe.returncode == 0:
        return
    log(f"本地没有 {SWIFT_IMAGE}，从镜像源拉取 {SWIFT_IMAGE_MIRROR}")
    run(["docker", "pull", SWIFT_IMAGE_MIRROR])
    run(["docker", "tag", SWIFT_IMAGE_MIRROR, SWIFT_IMAGE])


def run_docker(output_rel: str, *, insecure_git: bool) -> None:
    ensure_docker_image()
    env_args = [
        "-e",
        "WORK=/work",
        "-e",
        "CACHE_ROOT=/cache",
        "-e",
        f"OUTPUT_REL={output_rel}",
        "-e",
        f"GENERATOR_VERSION={GENERATOR_VERSION}",
    ]
    if insecure_git:
        # 仅当本机有 TLS 拦截代理、容器里的 git 拉不动 GitHub 时用；CI 不要加。
        env_args += ["-e", "GIT_SSL_NO_VERIFY=1"]
    run(
        [
            "docker",
            "run",
            "--rm",
            "-v",
            f"{to_docker_path(ROOT)}:/work",
            "-v",
            f"{to_docker_path(CACHE)}:/cache",
            *env_args,
            SWIFT_IMAGE,
            "bash",
            "-lc",
            generation_script(),
        ]
    )


def run_native(output_rel: str, *, insecure_git: bool) -> None:
    if shutil.which("swift") is None:
        raise ToolError("PATH 上没有 swift；用 --runner docker")
    if shutil.which("bash") is None:
        raise ToolError("native 后端需要 bash；Windows 上请用 --runner docker")
    env = dict(os.environ)
    env["WORK"] = ROOT.as_posix()
    env["CACHE_ROOT"] = CACHE.as_posix()
    env["OUTPUT_REL"] = output_rel
    env["GENERATOR_VERSION"] = GENERATOR_VERSION
    if insecure_git:
        env["GIT_SSL_NO_VERIFY"] = "1"
    run(["bash", "-lc", generation_script()], cwd=ROOT, env=env)


def normalize(text: str) -> str:
    """统一换行/结尾，保证同契约同输出（Windows 与 macOS 生成结果一致）。"""
    text = text.replace("\r\n", "\n").replace("\r", "\n").lstrip("\ufeff")
    return text.rstrip("\n") + "\n"


def post_process(output: Path) -> list[Path]:
    """给生成物加 `<auto-generated>` 头（审计工具据此跳过），并统一行尾。"""
    banner = BANNER.format(version=GENERATOR_VERSION)
    files = sorted(p for p in output.rglob("*") if p.is_file())
    for path in files:
        text = normalize(path.read_text(encoding="utf-8"))
        if "<auto-generated>" not in text.split("\n\n", 1)[0]:
            text = banner + text
        path.write_text(normalize(text), encoding="utf-8", newline="")
    return files


def sha256_short(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()[:12]


def describe(files: list[Path]) -> None:
    total = 0
    for path in files:
        lines = len(path.read_text(encoding="utf-8").splitlines())
        total += lines
        log(f"  {path.relative_to(ROOT).as_posix()}  {lines} 行  sha256:{sha256_short(path)}")
    log(f"共 {len(files)} 个文件 / {total} 行")


def generate_into(output: Path, runner: str, *, insecure_git: bool) -> None:
    if output.exists():
        shutil.rmtree(output)
    output.mkdir(parents=True, exist_ok=True)
    output_rel = output.relative_to(ROOT).as_posix()
    if runner == "docker":
        run_docker(output_rel, insecure_git=insecure_git)
    else:
        run_native(output_rel, insecure_git=insecure_git)
    report_diagnostics()


DIAGNOSTICS = CACHE / "diagnostics.yaml"


def report_diagnostics() -> None:
    """把生成器的 warnings（例如某个 schema 被跳过）打到 CI 日志里。

    生成器对不支持/有歧义的 schema 是“跳过 + 警告”而不是失败，所以不看诊断
    就可能在 SDK 里悄悄少掉字段。这里强制可视化。
    """
    if not DIAGNOSTICS.is_file():
        return
    text = DIAGNOSTICS.read_text(encoding="utf-8", errors="replace").strip()
    if not text:
        log("生成器诊断：无警告")
        return
    print("[gen-swift-sdk] 生成器诊断（warnings）：", flush=True)
    print(text, flush=True)


def swift_files(directory: Path) -> dict[str, str]:
    return {
        p.relative_to(directory).as_posix(): normalize(p.read_text(encoding="utf-8"))
        for p in sorted(directory.rglob("*"))
        if p.is_file()
    }


def first_difference(expected: str, actual: str) -> str:
    expected_lines = expected.splitlines()
    actual_lines = actual.splitlines()
    for index, (want, got) in enumerate(zip(expected_lines, actual_lines), start=1):
        if want != got:
            return f"第 {index} 行期望 {want!r}，实际 {got!r}"
    if len(expected_lines) != len(actual_lines):
        return f"行数不同：期望 {len(expected_lines)}，实际 {len(actual_lines)}"
    return "内容不同"


def check(runner: str, *, insecure_git: bool) -> int:
    scratch = CACHE / "check-out"
    log(f"重新生成到 {scratch.relative_to(ROOT).as_posix()} 做漂移校验")
    generate_into(scratch, runner, insecure_git=insecure_git)
    post_process(scratch)
    expected = swift_files(OUTPUT) if OUTPUT.exists() else {}
    actual = swift_files(scratch)
    problems: list[str] = []
    for name in sorted(set(expected) | set(actual)):
        if name not in actual:
            problems.append(f"{name}: 契约里有生成物，但仓库里缺失（请重新生成）")
        elif name not in expected:
            problems.append(f"{name}: 生成器多产出了文件，但仓库里没有")
        elif expected[name] != actual[name]:
            problems.append(
                f"{name}: 与生成结果不一致 —— {first_difference(actual[name], expected[name])}"
            )
    if problems:
        print("[gen-swift-sdk] 生成物与契约不一致（先跑一次生成器再提交）：", file=sys.stderr)
        for problem in problems:
            print(f"  - {problem}", file=sys.stderr)
        return 1
    log(f"生成物与契约一致（{len(expected)} 个文件）")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="contracts/openapi.yaml → sdks/swift/Sources/EliCloudSDK/Generated",
    )
    parser.add_argument("--check", action="store_true", help="只校验生成物是否与契约一致")
    parser.add_argument(
        "--runner",
        choices=("auto", "native", "docker"),
        default="auto",
        help="auto：有 swift 用 native，否则用 docker（默认）",
    )
    parser.add_argument(
        "--insecure-git",
        action="store_true",
        help="容器/原生拉取生成器时关闭 git TLS 校验（仅本机有 TLS 拦截代理时用）",
    )
    args = parser.parse_args(argv)

    runner = args.runner
    if runner == "auto":
        runner = "native" if shutil.which("swift") and shutil.which("bash") else "docker"

    CACHE.mkdir(parents=True, exist_ok=True)
    if not OPENAPI.is_file():
        print(f"找不到契约：{OPENAPI}", file=sys.stderr)
        return 2

    rewrites = derive_generator_input(OPENAPI, CACHE / DERIVED_INPUT_NAME)
    log(
        f"生成器输入：.local/gen-swift-sdk/{DERIVED_INPUT_NAME}"
        f"（可空 union 降级 {rewrites} 处；契约本身未改动）"
    )

    if args.check:
        return check(runner, insecure_git=args.insecure_git)

    generate_into(OUTPUT, runner, insecure_git=args.insecure_git)
    files = post_process(OUTPUT)
    describe(files)
    log(f"完成（runner={runner}，generator={GENERATOR_VERSION}）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
