"""gen-swift-sdk 的单元测试（不跑 Docker / 不需要 swift）。

覆盖：生成物后处理（banner、行尾统一、幂等）、漂移比较、版本 pin 一致性。
"""

from __future__ import annotations

import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import gen_swift_sdk as tool  # noqa: E402


class PostProcessTests(unittest.TestCase):
    def test_banner_is_prepended_once_and_lf_normalized(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp)
            target = out / "Client.swift"
            target.write_bytes(b"// Generated by swift-openapi-generator\r\nimport HTTPTypes\r\n")
            files = tool.post_process(out)
            self.assertEqual([p.name for p in files], ["Client.swift"])
            text = target.read_text(encoding="utf-8")
            self.assertTrue(text.startswith("// <auto-generated>"))
            self.assertIn("<auto-generated>", text.split("\n\n", 1)[0])
            self.assertNotIn("\r", text)
            self.assertTrue(text.endswith("\n"))
            # 幂等：再跑一次不会叠加 banner
            tool.post_process(out)
            self.assertEqual(target.read_text(encoding="utf-8"), text)

    def test_bom_is_stripped(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp)
            target = out / "Types.swift"
            target.write_text("\ufeffpublic struct A {}\n", encoding="utf-8")
            tool.post_process(out)
            text = target.read_text(encoding="utf-8")
            self.assertFalse(text.startswith("\ufeff"))
            self.assertIn("public struct A", text)


class DriftComparisonTests(unittest.TestCase):
    def test_first_difference_reports_line(self) -> None:
        self.assertIn("第 2 行", tool.first_difference("a\nb\n", "a\nc\n"))

    def test_swift_files_normalizes(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp)
            (out / "a.swift").write_bytes(b"x\r\n")
            self.assertEqual(tool.swift_files(out), {"a.swift": "x\n"})


class PinTests(unittest.TestCase):
    def test_runtime_pin_matches_generator_version(self) -> None:
        package = (tool.ROOT / "sdks" / "swift" / "Package.swift").read_text(encoding="utf-8")
        self.assertIn(f'exact: "{tool.GENERATOR_VERSION}"', package)

    def test_generation_script_uses_work_and_cache_roots(self) -> None:
        script = tool.generation_script()
        for token in ("$WORK/contracts/openapi.yaml", "$CACHE_ROOT", "$OUTPUT_REL"):
            self.assertIn(token, script)
        self.assertIn("--config", script)
        # swift-openapi-generator 的文档路径是位置参数；`--input` 不存在（会 exit 64）。
        self.assertNotIn("--input", script)


if __name__ == "__main__":
    unittest.main()
