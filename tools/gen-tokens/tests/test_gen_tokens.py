"""gen-tokens 的单元测试：快照稳定性 + 失败用例。

运行：
    python -m unittest discover -s tools/gen-tokens/tests -v
"""

from __future__ import annotations

import copy
import json
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "tools" / "shared"))

import designlib as dl  # noqa: E402

FIXTURE = ROOT / "tools" / "gen-tokens" / "tests" / "fixtures" / "valid"


def load_fixture() -> dict:
    return dl.load_tokens(FIXTURE / "tokens.json")


class SnapshotTests(unittest.TestCase):
    def test_fixture_is_valid(self) -> None:
        self.assertEqual(dl.validate(load_fixture()), [])

    def test_csharp_snapshot(self) -> None:
        self.assert_snapshot("DesignTokens.g.cs", dl.emit_csharp(load_fixture()))

    def test_swift_snapshot(self) -> None:
        self.assert_snapshot("DesignTokens.swift", dl.emit_swift(load_fixture()))

    def test_kotlin_snapshot(self) -> None:
        self.assert_snapshot("Tokens.kt", dl.emit_kotlin(load_fixture()))

    def test_python_snapshot(self) -> None:
        self.assert_snapshot("tokens.py", dl.emit_python(load_fixture()))

    def test_official_table_snapshot(self) -> None:
        self.assert_snapshot("official.md", dl.render_official_table(load_fixture()))

    def test_exception_table_snapshot(self) -> None:
        self.assert_snapshot("exceptions.md", dl.render_exception_table(load_fixture()))

    def assert_snapshot(self, name: str, actual: str) -> None:
        expected = (FIXTURE / "expected" / name).read_text(encoding="utf-8")
        self.assertEqual(expected, actual, f"{name} 与快照不一致；确认改动后重新生成快照")

    def test_generated_files_carry_header(self) -> None:
        doc = load_fixture()
        for text in (dl.emit_csharp(doc), dl.emit_swift(doc), dl.emit_kotlin(doc), dl.emit_python(doc)):
            self.assertIn("<auto-generated> from design/tokens.json", text)


class ValidationFailureTests(unittest.TestCase):
    def setUp(self) -> None:
        self.doc = load_fixture()

    def errors(self, doc: dict) -> list[str]:
        return dl.validate(doc)

    def test_missing_source(self) -> None:
        del self.doc["color"]["text"]["primary"]["source"]
        errors = self.errors(self.doc)
        self.assertTrue(any("缺少 source" in error for error in errors), errors)

    def test_official_without_ref(self) -> None:
        self.doc["color"]["text"]["primary"]["platforms"]["windows"] = {"source": "official"}
        errors = self.errors(self.doc)
        self.assertTrue(any("official 缺少可解析的 ref" in error for error in errors), errors)

    def test_custom_without_reason(self) -> None:
        space = self.doc["space"]["4"]
        self.assertIsInstance(space, dict)
        space.pop("reason")
        errors = self.errors(self.doc)
        self.assertTrue(any("custom 缺少 reason" in error for error in errors), errors)

    def test_missing_platform(self) -> None:
        self.doc["material"]["chrome"]["platforms"].pop("linux")
        errors = self.errors(self.doc)
        self.assertTrue(any("material.chrome[linux]: official 缺少可解析的 ref" in error for error in errors), errors)

    def test_bad_color_value(self) -> None:
        self.doc["brand"]["hero"]["scrim"]["value"] = "black"
        errors = self.errors(self.doc)
        self.assertTrue(any("颜色 value 必须是 #RRGGBB" in error for error in errors), errors)

    def test_unknown_source(self) -> None:
        self.doc["space"]["4"]["source"] = "vendor"
        errors = self.errors(self.doc)
        self.assertTrue(any("source 非法" in error for error in errors), errors)

    def test_wrong_platform_ref_shape(self) -> None:
        self.doc["color"]["text"]["primary"]["platforms"]["windows"]["ref"] = "@theme_fg_color"
        errors = self.errors(self.doc)
        self.assertTrue(any("不是合法的 WinUI" in error for error in errors), errors)

    def test_unknown_linux_style_class(self) -> None:
        self.doc["type"]["title"]["platforms"]["linux"]["ref"] = "not-a-real-class"
        errors = self.errors(self.doc)
        self.assertTrue(any("Adwaita style class" in error for error in errors), errors)

    def test_mixed_leaf_and_group(self) -> None:
        self.doc["color"]["text"]["primary"]["child"] = {}
        errors = self.errors(self.doc)
        self.assertTrue(any("不能同时是叶子和分组" in error for error in errors), errors)

    def test_duplicate_json_key_rejected(self) -> None:
        with self.assertRaises(dl.TokenError):
            dl.strict_json_load('{"version": 2, "color": {}, "color": {}}', "<test>")

    def test_incomplete_platforms_do_not_generate(self) -> None:
        self.doc["color"]["text"]["primary"]["platforms"].pop("windows")
        with self.assertRaises(dl.TokenError):
            dl.emit_csharp(self.doc)


class RealTokensTests(unittest.TestCase):
    def test_repository_tokens_are_valid(self) -> None:
        doc = dl.load_tokens(ROOT / "design" / "tokens.json")
        self.assertEqual(dl.validate(doc), [])

    def test_every_platform_has_a_symbol_or_comment(self) -> None:
        doc = dl.load_tokens(ROOT / "design" / "tokens.json")
        for path, entry in dl.iter_leaves(doc):
            for platform in dl.PLATFORMS:
                resolved = dl.resolve_platform(entry, platform)
                if resolved["source"] == "official":
                    self.assertTrue(resolved["ref"].strip(), f"{dl.token_id(path)}[{platform}] ref 为空")
                else:
                    for field in ("reason", "approvedBy", "scope"):
                        self.assertTrue(str(resolved.get(field, "")).strip(), f"{dl.token_id(path)}[{platform}] 缺 {field}")


if __name__ == "__main__":
    unittest.main()
